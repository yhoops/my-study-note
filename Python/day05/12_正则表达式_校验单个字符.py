"""
正则表达式介绍：

概述：
正确的，符合特定规则的字符串。
Regular Expression，正则表达式，简称：re
（正则表达式是一种强大的文本匹配工具，用特定的“规则字符串”来描述、匹配、查找或替换符合某种模式的文本。它不是某一种编程语言独有的，而是通用的模式匹配语言。）

细节：

学正则表达式，就是学正则表达式的规则，你用不背，网上一搜一大堆。 （核心是理解常用元字符、字符集、量词和分组的含义，遇到复杂需求时查文档或在线工具测试即可，不需要死记硬背所有规则。）
关于正则我对大家的要求是，能用我们讲的规则，看懂别人写的式子，且会简单修改即可。 （目标是“读得懂 + 能小改”，而不是一开始就追求写出复杂正则。看懂别人的正则并做简单调整，已经能解决绝大多数实际开发中的文本处理问题。）
正则不独属于Python，像Java、JavaScript、PHP、Go等都支持。 （几乎所有主流编程语言都内置或通过库支持正则表达式，规则高度通用。学会一套规则后，换语言时只需要适配对应的API写法即可。）
步骤：

导包 import re
正则匹配 result = re.match('正则表达式', '要校验的字符串') （re.match() 从字符串开头开始匹配。如果匹配成功返回Match对象，失败返回None。常用的还有 re.search()、re.findall()、re.sub() 等。）
获取匹配结果. result.group() （如果匹配成功，result.group() 返回完整匹配的字符串；result.group(1)、result.group(2) 可获取分组内容。也可使用 result.groups() 获取所有分组。）
正则常用的规则：
.          代表任意的 1个字符，除了 \n
.         取消.的特殊含义，就是1个普通的.
a          代表1个普通的字符 a
[abc]      代表a,b,c中任意的1个字符
[^abc]     代表除了a,b,c外，任意的1个字符
\d         代表数字，等价于 [0-9]
\D         代表非数字，等价于 [^0-9]

（补充常用规则，方便扩展使用：
\w         代表字母、数字、下划线，汉字，等价于 [a-zA-Z0-9_汉字]
\W         代表非字母数字下划线(特殊符号)
\s         代表空白字符（空格、制表符\t、换行\n等）
\S         代表非空白字符

.* 任意多个字符，可以0次

前面的字符出现0次或多次
前面的字符出现1次或多次 ? 前面的字符出现0次或1次 {n} 前面的字符恰好出现n次 {n,m} 前面的字符出现n到m次 ^ 匹配字符串开头 $ 匹配字符串结尾 () 分组，提取匹配内容或改变优先级 | 或关系，例如 a|b 匹配a或b ）
"""

# 需求：正则入门
"""
    re.match("正则表达式", "要校验的字符串")    这个是从头开始匹配的
    re.search("正则表达式", "要校验的字符串")   这个是从任意位置开始匹配，只要字符串中任意位置有符合就可以
    re.findall("正则表达式", "要校验的字符串")  这个是从头开始匹配，返回一个列表

"""


# 1. 导包
import re

# 2. 正则校验.  参1：正则规则 参2：要被校验的字符串
result = re.match(".it", "ait")  # 匹配成功
result = re.match("\.it", "ait")  # 匹配失败
result = re.match("[ahg]it", "sit")  # 匹配失败
result = re.match("[^ahg]it", "sit")  # 匹配成功
result = re.match("\dit", "9itsds")  # 匹配成功
result = re.match("[3-7]it", "5it")  # 匹配成功，[3-7]等价为[34567]

result = re.match("a\dhm", "a1hm")  # 匹配成功
result = re.match("a\dhm", "a10hm")  # 匹配失败
result = re.match("a\Dhm", "a!hm")  # 匹配成功

result = re.match("a\shm", "a 1hm")  # 匹配成功
result = re.match("a\shm", "a  1hm")  # 匹配失败

result = re.match("a\whm", "a_hm")  # 匹配成功
result = re.match("a\whm", "a夯hm")  # 匹配成功
result = re.match("a\Whm", "a\\hm")  # 匹配成功

# 3. 获取匹配结果
if result:
    print(result.group())
else:
    print("匹配失败")
